import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import {Bill, BusinessProfile, LedgerRow, Party} from '../types';
import {
  formatDisplayDate,
  formatINR,
  formatMonthLabel,
  formatRsPDF,
  sanitizePhoneForWhatsApp,
} from './formatters';

function addFooterBranding(doc: jsPDF) {
  const pageCount = doc.getNumberOfPages();
  const pageHeight = doc.internal.pageSize.getHeight();
  const pageWidth = doc.internal.pageSize.getWidth();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setDrawColor(226, 232, 240);
    doc.line(14, pageHeight - 16, pageWidth - 14, pageHeight - 16);
    doc.setFontSize(8.5);
    doc.setTextColor(5, 150, 105);
    doc.setFont('helvetica', 'bold');
    doc.text('Generated by GREEN BILL BOOK', 14, pageHeight - 10);
    doc.setTextColor(100, 116, 139);
    doc.setFont('helvetica', 'normal');
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 14, pageHeight - 10, {align: 'right'});
  }
}

export function createInvoicePDF(bill: Bill, profile: BusinessProfile, party?: Party): jsPDF {
  const doc = new jsPDF({unit: 'mm', format: 'a4'});
  const pageWidth = doc.internal.pageSize.getWidth();

  // Emerald Header Bar
  doc.setFillColor(5, 150, 105);
  doc.rect(0, 0, pageWidth, 6, 'F');

  // Business Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text(profile.businessName || 'Green Bill Book Store', 14, 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  let y = 24;
  if (profile.address) {
    const addrLines = doc.splitTextToSize(profile.address, 105);
    doc.text(addrLines, 14, y);
    y += addrLines.length * 4.2;
  }
  const contactLine = [
    profile.phone ? `Ph: ${profile.phone}` : '',
    profile.gstin ? `GSTIN: ${profile.gstin}` : '',
  ]
    .filter(Boolean)
    .join('  |  ');
  if (contactLine) {
    doc.text(contactLine, 14, y);
    y += 5;
  }

  // Invoice Title Box on Right
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(5, 150, 105);
  doc.text(bill.type === 'sale' ? 'TAX INVOICE' : 'PURCHASE BILL', pageWidth - 14, 18, {
    align: 'right',
  });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(15, 23, 42);
  doc.text(`Bill No: ${bill.billNumber}`, pageWidth - 14, 25, {align: 'right'});
  doc.text(`Date: ${formatDisplayDate(bill.date)}`, pageWidth - 14, 30, {align: 'right'});
  doc.text(`Mode: ${bill.paymentMode}`, pageWidth - 14, 35, {align: 'right'});

  const dividerY = Math.max(y + 3, 41);
  doc.setDrawColor(226, 232, 240);
  doc.line(14, dividerY, pageWidth - 14, dividerY);

  // Party Info
  let py = dividerY + 6;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(bill.type === 'sale' ? 'BILL TO:' : 'SUPPLIER:', 14, py);
  py += 5;
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(bill.partyName, 14, py);
  py += 4.8;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  if (bill.partyPhone) {
    doc.text(`Phone: ${bill.partyPhone}`, 14, py);
    py += 4.5;
  }
  if (party?.address) {
    const pAddr = doc.splitTextToSize(party.address, 120);
    doc.text(pAddr, 14, py);
    py += pAddr.length * 4.2;
  }
  if (party?.gstin) {
    doc.text(`GSTIN: ${party.gstin}`, 14, py);
    py += 4.5;
  }

  // Items Table
  const tableRows = bill.items.map((item, idx) => [
    String(idx + 1),
    item.name,
    `${item.qty} ${item.unit}`,
    formatRsPDF(item.rate),
    item.discountAmount > 0 ? formatRsPDF(item.discountAmount) : '-',
    item.gstPercent > 0 ? `${item.gstPercent}% (${formatRsPDF(item.gstAmount)})` : '0%',
    formatRsPDF(item.total),
  ]);

  autoTable(doc, {
    startY: py + 3,
    head: [['#', 'Item Description', 'Qty / Unit', 'Rate', 'Disc', 'GST', 'Amount']],
    body: tableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [5, 150, 105],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
    },
    bodyStyles: {
      fontSize: 8.5,
      textColor: [15, 23, 42],
    },
    columnStyles: {
      0: {cellWidth: 9, halign: 'center'},
      2: {halign: 'right'},
      3: {halign: 'right'},
      4: {halign: 'right'},
      5: {halign: 'right'},
      6: {halign: 'right', fontStyle: 'bold'},
    },
    margin: {left: 14, right: 14, bottom: 24},
  });

  // Summary Block
  const finalY = (doc as unknown as {lastAutoTable: {finalY: number}}).lastAutoTable.finalY + 6;
  const rightColX = pageWidth - 14;
  const labelColX = pageWidth - 75;
  let sy = finalY;

  doc.setFontSize(9.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);

  doc.text('Subtotal:', labelColX, sy);
  doc.text(formatRsPDF(bill.subtotal), rightColX, sy, {align: 'right'});
  sy += 5.5;

  if (bill.totalDiscount > 0) {
    doc.text('Discount:', labelColX, sy);
    doc.text(`- ${formatRsPDF(bill.totalDiscount)}`, rightColX, sy, {align: 'right'});
    sy += 5.5;
  }

  if (bill.totalGst > 0) {
    doc.text('CGST + SGST:', labelColX, sy);
    doc.text(formatRsPDF(bill.totalGst), rightColX, sy, {align: 'right'});
    sy += 5.5;
  }

  doc.setDrawColor(203, 213, 225);
  doc.line(labelColX, sy - 1.5, rightColX, sy - 1.5);
  sy += 3.5;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('Grand Total:', labelColX, sy);
  doc.text(formatRsPDF(bill.grandTotal), rightColX, sy, {align: 'right'});
  sy += 6;

  doc.setFontSize(9.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(5, 150, 105);
  doc.text('Paid Amount:', labelColX, sy);
  doc.text(formatRsPDF(bill.paidAmount), rightColX, sy, {align: 'right'});
  sy += 5.5;

  if (bill.balanceDue > 0) {
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(220, 38, 38);
    doc.text('Balance (Udhar):', labelColX, sy);
    doc.text(formatRsPDF(bill.balanceDue), rightColX, sy, {align: 'right'});
    sy += 6;
  }

  // Left side terms & UPI
  let ty = finalY;
  if (profile.upiId) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text(`UPI ID: ${profile.upiId}`, 14, ty);
    ty += 5.5;
  }
  if (bill.notes) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(71, 85, 105);
    const noteLines = doc.splitTextToSize(`Note: ${bill.notes}`, 95);
    doc.text(noteLines, 14, ty);
    ty += noteLines.length * 4.2 + 2;
  }
  if (profile.terms) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(71, 85, 105);
    doc.text('Terms & Conditions:', 14, ty);
    ty += 4;
    doc.setFont('helvetica', 'normal');
    const termLines = doc.splitTextToSize(profile.terms, 95);
    doc.text(termLines, 14, ty);
  }

  addFooterBranding(doc);
  return doc;
}

export function createLedgerPDF(params: {
  party: Party;
  profile: BusinessProfile;
  rows: LedgerRow[];
  openingForPeriod: number;
  closingBalance: number;
  fromDate?: string;
  toDate?: string;
}): jsPDF {
  const {party, profile, rows, openingForPeriod, closingBalance, fromDate, toDate} = params;
  const doc = new jsPDF({unit: 'mm', format: 'a4'});
  const pageWidth = doc.internal.pageSize.getWidth();

  doc.setFillColor(5, 150, 105);
  doc.rect(0, 0, pageWidth, 6, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(15, 23, 42);
  doc.text(profile.businessName || 'Green Bill Book', 14, 17);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(5, 150, 105);
  doc.text('PARTY KHATA STATEMENT', pageWidth - 14, 17, {align: 'right'});

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Party: ${party.name} (${party.phone || 'No phone'})`, 14, 24);
  if (party.address) {
    doc.text(`Address: ${party.address}`, 14, 29);
  }

  const periodLabel =
    fromDate || toDate
      ? `Period: ${fromDate ? formatDisplayDate(fromDate) : 'Start'} to ${
          toDate ? formatDisplayDate(toDate) : 'Today'
        }`
      : 'Period: All Transactions';
  doc.text(periodLabel, pageWidth - 14, 24, {align: 'right'});

  const balanceText =
    closingBalance > 0
      ? `Net Receivable (Lena Hai): ${formatRsPDF(closingBalance)}`
      : closingBalance < 0
      ? `Net Payable (Dena Hai): ${formatRsPDF(Math.abs(closingBalance))}`
      : 'Account Settled (Rs. 0.00)';
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(closingBalance >= 0 ? 5 : 220, closingBalance >= 0 ? 150 : 38, closingBalance >= 0 ? 105 : 38);
  doc.text(balanceText, pageWidth - 14, 30, {align: 'right'});

  const tableBody: string[][] = [
    [
      '-',
      'Opening Balance',
      fromDate ? `Carried forward before ${formatDisplayDate(fromDate)}` : 'Initial Balance',
      '-',
      `${formatRsPDF(Math.abs(openingForPeriod))} ${openingForPeriod >= 0 ? 'Dr' : 'Cr'}`,
    ],
    ...rows.map((r) => [
      formatDisplayDate(r.date),
      r.title,
      r.subtitle,
      `${r.balanceImpact >= 0 ? '+' : ''}${formatRsPDF(r.balanceImpact)}`,
      `${formatRsPDF(Math.abs(r.runningBalance))} ${r.runningBalance >= 0 ? 'Dr' : 'Cr'}`,
    ]),
  ];

  autoTable(doc, {
    startY: 36,
    head: [['Date', 'Particulars', 'Details', 'Balance Impact', 'Running Balance']],
    body: tableBody,
    theme: 'grid',
    headStyles: {
      fillColor: [5, 150, 105],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
    },
    bodyStyles: {fontSize: 8.5, textColor: [15, 23, 42]},
    columnStyles: {
      3: {halign: 'right'},
      4: {halign: 'right', fontStyle: 'bold'},
    },
    margin: {left: 14, right: 14, bottom: 24},
  });

  addFooterBranding(doc);
  return doc;
}

export function createMonthlyPLPDF(params: {
  monthKey: string;
  profile: BusinessProfile;
  salesRevenue: number;
  taxableSales: number;
  gstCollected: number;
  cogs: number;
  totalPurchases: number;
  netProfit: number;
  profitMarginPct: number;
  saleCount: number;
  purchaseCount: number;
  topItems: Array<{name: string; qtySold: number; unit: string; revenue: number; profit: number}>;
}): jsPDF {
  const doc = new jsPDF({unit: 'mm', format: 'a4'});
  const pageWidth = doc.internal.pageSize.getWidth();
  const monthTitle = formatMonthLabel(params.monthKey);

  doc.setFillColor(5, 150, 105);
  doc.rect(0, 0, pageWidth, 6, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(15, 23, 42);
  doc.text(params.profile.businessName || 'Green Bill Book', 14, 17);

  doc.setFontSize(12);
  doc.setTextColor(5, 150, 105);
  doc.text(`PROFIT & LOSS REPORT — ${monthTitle.toUpperCase()}`, pageWidth - 14, 17, {
    align: 'right',
  });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  if (params.profile.address) {
    doc.text(params.profile.address, 14, 23);
  }

  autoTable(doc, {
    startY: 32,
    head: [['Profit & Loss Metric', 'Details', 'Amount']],
    body: [
      ['Total Monthly Sales Revenue (Incl. GST)', `${params.saleCount} sale bills`, formatRsPDF(params.salesRevenue)],
      ['Taxable Sales Value (Excl. GST)', 'Net goods revenue', formatRsPDF(params.taxableSales)],
      ['GST Collected on Sales', 'Output tax', formatRsPDF(params.gstCollected)],
      ['Cost of Goods Sold (COGS)', 'Based on item purchase cost', formatRsPDF(params.cogs)],
      ['Total Monthly Purchase Bills', `${params.purchaseCount} purchase bills`, formatRsPDF(params.totalPurchases)],
      [
        params.netProfit >= 0 ? 'Gross / Net Profit' : 'Net Loss',
        `Profit Margin: ${params.profitMarginPct.toFixed(1)}%`,
        formatRsPDF(params.netProfit),
      ],
    ],
    theme: 'grid',
    headStyles: {
      fillColor: [5, 150, 105],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9,
    },
    bodyStyles: {fontSize: 9, textColor: [15, 23, 42]},
    columnStyles: {2: {halign: 'right', fontStyle: 'bold'}},
    margin: {left: 14, right: 14},
  });

  if (params.topItems.length > 0) {
    const startY = (doc as unknown as {lastAutoTable: {finalY: number}}).lastAutoTable.finalY + 10;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text('Item-Wise Profit Breakdown', 14, startY);

    autoTable(doc, {
      startY: startY + 4,
      head: [['Item Name', 'Qty Sold', 'Sales Value', 'Estimated Profit']],
      body: params.topItems.map((it) => [
        it.name,
        `${it.qtySold} ${it.unit}`,
        formatRsPDF(it.revenue),
        formatRsPDF(it.profit),
      ]),
      theme: 'grid',
      headStyles: {
        fillColor: [15, 23, 42],
        textColor: [255, 255, 255],
        fontSize: 8.5,
      },
      bodyStyles: {fontSize: 8.5},
      columnStyles: {
        1: {halign: 'right'},
        2: {halign: 'right'},
        3: {halign: 'right', fontStyle: 'bold'},
      },
      margin: {left: 14, right: 14, bottom: 24},
    });
  }

  addFooterBranding(doc);
  return doc;
}

export async function sharePDFOnWhatsApp(params: {
  doc: jsPDF;
  filename: string;
  phone?: string;
  summaryText: string;
  title: string;
}): Promise<'shared' | 'downloaded_and_wa'> {
  const {doc, filename, phone, summaryText, title} = params;
  const blob = doc.output('blob');
  const file = new File([blob], filename, {type: 'application/pdf'});

  const nav = navigator as Navigator & {
    canShare?: (data: ShareData) => boolean;
  };

  if (nav.share && nav.canShare && nav.canShare({files: [file]})) {
    try {
      await nav.share({
        title,
        text: summaryText,
        files: [file],
      });
      return 'shared';
    } catch (err) {
      if ((err as Error)?.name === 'AbortError') {
        return 'shared';
      }
    }
  }

  // Fallback: Download PDF + open WhatsApp deep link with prefilled phone & summary
  doc.save(filename);
  const waPhone = sanitizePhoneForWhatsApp(phone || '');
  const encodedText = encodeURIComponent(summaryText);
  const waUrl = waPhone
    ? `https://wa.me/${waPhone}?text=${encodedText}`
    : `https://wa.me/?text=${encodedText}`;

  const link = document.createElement('a');
  link.href = waUrl;
  link.target = '_blank';
  link.rel = 'noopener noreferrer';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);

  return 'downloaded_and_wa';
}

export function openWhatsAppReminder(params: {
  partyName: string;
  phone: string;
  amount: number;
  businessName: string;
  upiId?: string;
}) {
  const waPhone = sanitizePhoneForWhatsApp(params.phone);
  const msg = `Namaste ${params.partyName},\n\nFriendly reminder from *${params.businessName}*: your pending Udhar balance is *${formatINR(
    params.amount,
    true
  )}*.${params.upiId ? `\nUPI ID: ${params.upiId}` : ''}\n\nThank you!\n_Sent via Green Bill Book_`;
  const url = waPhone
    ? `https://wa.me/${waPhone}?text=${encodeURIComponent(msg)}`
    : `https://wa.me/?text=${encodeURIComponent(msg)}`;
  const link = document.createElement('a');
  link.href = url;
  link.target = '_blank';
  link.rel = 'noopener noreferrer';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
